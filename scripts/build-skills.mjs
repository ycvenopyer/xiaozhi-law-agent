import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const skillsRoot = path.join(root, 'agent-skills');
const catalog = [];
const instructions = {};

// Intentionally accept the small YAML subset used by our checked-in skills.
// Unsupported metadata fails the build instead of silently changing routing.
function scalar(value) {
  return value.startsWith('"') ? JSON.parse(value) : value.trim();
}
for (const dir of (await readdir(skillsRoot, { withFileTypes: true })).filter(dir => dir.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const source = await readFile(path.join(skillsRoot, dir.name, 'SKILL.md'), 'utf8');
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]+)$/);
  if (!match) throw new Error(`${dir.name}: SKILL.md requires frontmatter and instructions`);
  const meta = Object.fromEntries(match[1].split(/\r?\n/).map(line => {
    const field = line.match(/^(name|description):\s*(.+)$/);
    if (!field) throw new Error(`${dir.name}: unsupported frontmatter`);
    return [field[1], scalar(field[2])];
  }));
  if (meta.name !== dir.name || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(meta.name) || meta.name.length > 64 || !meta.description) throw new Error(`${dir.name}: invalid skill identity`);
  const uiSource = await readFile(path.join(skillsRoot, dir.name, 'agents/openai.yaml'), 'utf8');
  if (uiSource.trim().split(/\r?\n/)[0] !== 'interface:') throw new Error(`${dir.name}: UI metadata must start with interface:`);
  const ui = {};
  for (const line of uiSource.trim().split(/\r?\n/).slice(1)) {
    const field = line.match(/^  (display_name|short_description|default_prompt):\s*(".*")$/);
    if (!field) throw new Error(`${dir.name}: unsupported UI metadata`);
    ui[field[1]] = scalar(field[2]);
  }
  if (!ui.display_name || !ui.short_description || !ui.default_prompt) throw new Error(`${dir.name}: missing UI metadata`);
  const body = match[2].trim();
  if (body.length > 12000) throw new Error(`${dir.name}: move long instructions into supported resources first`);
  catalog.push({ id: meta.name, name: ui.display_name, description: meta.description, summary: ui.short_description, starter: ui.default_prompt });
  instructions[meta.name] = body;
}
if (!catalog.length) throw new Error('No skills found');
const banner = '// Generated by scripts/build-skills.mjs. Edit agent-skills/* instead.\n';
const catalogCode = `export const SKILL_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\nexport type SkillId = typeof SKILL_CATALOG[number]['id'];\nexport type SkillInfo = typeof SKILL_CATALOG[number];\nexport function findSkill(id?: string) { return SKILL_CATALOG.find(skill => skill.id === id); }\n`;
const outputs = [
  ['shared/skill-catalog.generated.ts', banner + catalogCode],
  ['backend/src/modules/agent/skill-instructions.generated.ts', `${banner}${catalogCode}export const SKILL_INSTRUCTIONS: Record<string, string> = ${JSON.stringify(instructions, null, 2)};\n`],
];
for (const [relative, content] of outputs) {
  const filename = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (await readFile(filename, 'utf8') !== content) throw new Error(`${relative} is stale; run npm run skills:build`);
  } else await writeFile(filename, content, 'utf8');
}
console.log(`Validated ${catalog.length} agent skills${process.argv.includes('--check') ? '' : ' and generated registries'}.`);
