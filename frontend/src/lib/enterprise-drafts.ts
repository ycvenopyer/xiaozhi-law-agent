export function enterpriseDraftPrompt(template: DraftTemplate, entries: string[]) {
  return [
    template.name,
    '你是企业法务的文书起草助理。根据下列事实起草可编辑的 Markdown 初稿，仅输出文书正文。' + template.structure,
    '仅采用提供的事实、金额、届期、证据及依据。缺失项以【待补充】标明，引用依据应标注复核状态。把事实、主张和约定写清楚，保留必要的签署位置。',
    ...template.fields.map((label, index) => label + '：' + (entries[index]?.trim() || '待补充')),
  ].join('\n\n');
}
