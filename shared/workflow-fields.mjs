export const choices = {
  compare: ['商标检索比对', '著作权材料比对', '专利 FTO 初筛'],
  infringement: ['商标侵权', '著作权侵权', '商业秘密侵害', '专利检索提示'],
  compliance: [
    '研发合规清单',
    '开源许可证',
    '职务发明权属',
    '商业秘密保护',
    '竞业限制',
    '成果保护策略',
    '合同合规审查',
    '一般咨询',
  ],
  draft: ['保密协议（NDA）', '知识产权许可合同', '职务发明权属约定', '竞业限制协议'],
}
export function fieldNames(mode, task) {
  if (task === '专利 FTO 初筛' || task === '专利检索提示') return ['技术方案', '目标市场', '排除词']
  if (task === '研发合规清单') return ['项目名称', '项目情况']
  if (mode === 'infringement')
    return [
      '权利基础、登记号或底稿',
      '被诉行为、地域及比对材料',
      '行为发生时间',
      '双方关系或许可情况',
      '警告及后续行为',
      '已采取措施',
    ]
  if (mode === 'compare')
    return [
      '权利或作品材料 A',
      '拟使用标识或作品材料 B',
      '商品类别、渠道或使用方式',
      '使用地域、发生时间及是否商用',
    ]
  if (mode === 'draft')
    return [
      '当事人及角色',
      '成果、合作事项与使用范围',
      '期限、地域、价款或补偿',
      '归属、保密及违约要求',
    ]
  switch (task) {
    case '开源许可证':
      return ['组件、版本与许可证原文', '集成、修改及分发方式', '产品用途与拟采用许可证']
    case '成果保护策略':
    case '职务发明权属':
      return ['研发成果形态及贡献人', '雇佣、委托或合作约定', '是否已公开、公开时间及保密措施']
    case '合同合规审查':
      return ['合同类型（保密、许可或竞业）', '脱敏合同全文', '关键交易事实与审查目标']
    case '竞业限制':
      return ['人员职责及接触的信息', '约定范围、期限、地域与补偿', '履行情况及时间']
    case '商业秘密保护':
      return ['信息类别与商业价值', '知悉范围与保密措施', '披露、使用或可能泄露的事实']
    default:
      return ['具体问题及事实', '需要确认的问题或期望行动']
  }
}

